// node test/model.test.js — exercises Model.js without a QML runtime.
const fs = require("fs")
const path = require("path")
const assert = require("assert")
const src = fs.readFileSync(path.join(__dirname, "..", "Model.js"), "utf8")
const M = new Function(src + "; return { countText, wheelSteps, overlayAction, overlayCommand, steamSway, panelKey, weekPeak, unlockedCount, scaleRecipe, clock, totalTime, stepIndex, score, filterRecipes, ratioText, CUP_EMPTY, CUP_FULL }")()

assert.strictEqual(M.countText({ cups: 3, mg: 141.6 }, true, false), "3 · 142mg")
assert.strictEqual(M.countText({ cups: 3, mg: 141.6 }, false, false), "3")
assert.strictEqual(M.countText({ cups: 2, mg: 90 }, true, true), "2\n90")
assert.strictEqual(M.countText({}, true, false), "0")
assert.strictEqual(M.countText({ cups: 3, mg: 140, showMg: false }, true, false), "3")
assert.strictEqual(M.countText({ cups: 3, mg: 140, showCups: false }, true, false), "140mg")
assert.strictEqual(M.countText({ cups: 3, mg: 140, showCups: false, showMg: false }, true, false), "")

assert.deepStrictEqual(M.wheelSteps(0, -120), { steps: 1, rest: 0 })
assert.deepStrictEqual(M.wheelSteps(0, 240), { steps: -2, rest: 0 })
assert.deepStrictEqual(M.wheelSteps(100, 30), { steps: -1, rest: 10 })
assert.deepStrictEqual(M.wheelSteps(0, 40), { steps: 0, rest: 40 })

assert.strictEqual(M.overlayAction("Return", ""), "enter")
assert.strictEqual(M.overlayAction("Escape", ""), "skip")
assert.strictEqual(M.overlayAction("", "R"), "recipe")
assert.strictEqual(M.overlayAction("", "s"), "snooze")
assert.strictEqual(M.overlayAction("", "x"), "")

const p = { mode: "decaf", breakMin: 5, snoozeMin: 15, recipe: { id: "kasuya-4-6" } }
assert.deepStrictEqual(M.overlayCommand("enter", "cli", p), ["cli", "break", "start", "5", "--decaf"])
assert.deepStrictEqual(M.overlayCommand("enter", "cli", { breakMin: 7 }), ["cli", "break", "start", "7"])
assert.deepStrictEqual(M.overlayCommand("recipe", "cli", p), ["cli", "brew", "kasuya-4-6", "--window"])
assert.deepStrictEqual(M.overlayCommand("recipe", "cli", {}), [])
assert.deepStrictEqual(M.overlayCommand("snooze", "cli", p), ["cli", "break", "snooze", "15"])
assert.deepStrictEqual(M.overlayCommand("skip", "cli", p), ["cli", "break", "skip"])

assert.ok(Math.abs(M.steamSway(0, 0, 1)) <= 1)
assert.strictEqual(M.CUP_EMPTY.codePointAt(0), 0xF06CA)
assert.strictEqual(M.CUP_FULL.codePointAt(0), 0xF0176)
assert.strictEqual(M.panelKey("C"), "cup")
assert.strictEqual(M.panelKey("u"), "undo")
assert.strictEqual(M.panelKey("z"), "")
assert.strictEqual(M.weekPeak([]), 1)
assert.strictEqual(M.weekPeak([{ cups: 2 }, { cups: 7 }]), 7)
assert.strictEqual(M.unlockedCount([{ unlocked: true }, { unlocked: false }, { unlocked: true }]), 2)
const r46 = { dose_g: 20, water_ml: 300, steps: [{ at: 0, target_g: 50 }, { at: 45, target_g: 120 }, { at: 210, kind: "stop" }] }
const s30 = M.scaleRecipe(r46, 30)
assert.strictEqual(s30.water_ml, 450)
assert.deepStrictEqual(s30.steps.map(s => s.target_g), [75, 180, undefined])
assert.strictEqual(r46.water_ml, 300)
assert.strictEqual(M.clock(95), "1:35")
assert.strictEqual(M.clock(43200), "12h00")
assert.strictEqual(M.totalTime(r46), 210)
assert.strictEqual(M.stepIndex(r46.steps, 50), 1)
assert.strictEqual(M.stepIndex(r46.steps, -1), -1)
assert.strictEqual(M.score({ ratings: [{ overall: 4 }, { overall: 5 }] }), 4.5)
assert.strictEqual(M.score({}), null)
const list = [{ name: "B", status: "to_try", method: "V60" }, { name: "A", status: "favorite", method: "Espresso" }]
assert.deepStrictEqual(M.filterRecipes(list, "", "all").map(r => r.name), ["A", "B"])
assert.deepStrictEqual(M.filterRecipes(list, "v60", "all").map(r => r.name), ["B"])
assert.strictEqual(M.ratioText(18, 36), "1:2")
console.log("model.test.js: all assertions passed")
